export function SocialIcon({
  platform,
  icon,
  iconUrl,
  className
}: {
  platform?: string;
  icon?: string;
  iconUrl?: string;
  className?: string;
}) {
  if (iconUrl?.trim()) {
    return (
      <img
        src={iconUrl}
        alt=""
        aria-hidden="true"
        className={cn("h-4 w-4 object-contain", className)}
      />
    );
  }

  const key = icon?.trim().toLowerCase();
  if (key && key in LUCIDE) {
    const Glyph = LUCIDE[key as SocialIconKey];
    return <Glyph className={className} />;
  }

  const p = (platform ?? "").toLowerCase();
  if (p.includes("github") || p === "gh") return <GithubGlyph className={className} />;
  if (p.includes("linkedin")) return <LinkedinGlyph className={className} />;
  if (p.includes("whatsapp")) return <Glyph path={PATHS.whatsapp} className={className} />;
  if (p.includes("telegram")) return <Glyph path={PATHS.telegram} className={className} />;
  if (p.includes("upwork")) return <Glyph path={PATHS.upwork} className={className} />;
  if (p.includes("fiverr")) return <Glyph path={PATHS.fiverr} className={className} />;
  if (p.includes("freelanc")) return <Glyph path={PATHS.freelancer} className={className} />;
  if (p.includes("mostaql")) return <MostaqlGlyph className={className} />;
  if (p.includes("khamsat"))
    return <Glyph path={PATHS.khamsat} viewBox="0 0 1080 1080" className={className} />;
  if (p.includes("leetcode")) return <Glyph path={PATHS.leetcode} className={className} />;
  if (p.includes("stackoverflow") || p.includes("stack overflow"))
    return <Glyph path={PATHS.stackoverflow} className={className} />;
  if (p.includes("x") || p.includes("twitter"))
    return <Glyph path={PATHS.x} className={className} />;
  if (p.includes("instagram")) return <Glyph path={PATHS.instagram} className={className} />;
  if (p.includes("dribbble")) return <Glyph path={PATHS.dribbble} className={className} />;
  if (p === "email" || p === "mail") return <Mail className={cn("h-4 w-4", className)} />;
  if (p.includes("phone")) return <Phone className={cn("h-4 w-4", className)} />;
  if (p.includes("website") || p.includes("site"))
    return <Globe className={cn("h-4 w-4", className)} />;
  return <Link2 className={cn("h-4 w-4", className)} />;
}
